export function voiceMessage(language, key, values = {}) {
  const template = (VOICE_MESSAGES[language] || VOICE_MESSAGES.it)[key] || VOICE_MESSAGES.it[key] || key;
  return template.replace(/\{(\w+)\}/g, (match, name) => values[name] == null ? match : String(values[name]));
}

export function buildWordImportSummaryDialog(summary, language = 'it') {
  const voices = summary.characters || [];
  const preview = voices.slice(0, 12).join(', ');
  const extra = Math.max(0, voices.length - 12);
  const t = (key) => voiceMessage(language, key);
  return {
    title: t('importTitle'),
    autoTranslate: false,
    message: [
      `${t('project')}: ${summary.title}`,
      `${t('elements')}: ${summary.total}`,
      `${t('dialogue')}: ${summary.dialogue}`,
      `${t('directions')}: ${summary.stageDirections}`,
      `${t('unassigned')}: ${summary.unassigned || 0}`,
      `${t('recognized')}: ${voices.length}`,
      preview ? `${t('firstVoices')}: ${preview}${extra ? `, +${extra}` : ''}` : '',
    ].filter(Boolean).join('\n'),
  };
}
